package com.immortal.launcher

import java.io.File
import java.io.IOException
import java.lang.reflect.InvocationTargetException
import java.net.InetAddress
import java.net.ServerSocket
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.atomic.AtomicReference
import org.junit.Assert.*
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.junit.runners.Parameterized

/** Generated bytes over real TCP; no package installation or owner APK involved. */
@RunWith(Parameterized::class)
class ApkDownloadTransportTest(private val consumer: String) {
  @get:Rule val files = TemporaryFolder()
  private val original = byteArrayOf(7, 8, 9, 10)
  private val body = ByteArray(32_769) { (it % 251).toByte() }

  @Test fun truncatedDownloadPreservesPreviousFile() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    var failure: Throwable? = null
    response(body.copyOf(123), body.size.toLong()) { url ->
      failure = runCatching { download(url, target) }.exceptionOrNull()
    }
    assertArrayEquals("A failed transfer must retain the original four bytes", original, target.readBytes())
    assertTrue("Incomplete transfer must fail", failure is IOException)
    assertEntries("cached.apk")
  }

  @Test fun truncatedDownloadDoesNotPublishANewFile() {
    val target = File(files.root, "new.apk")
    response(body.copyOf(123), body.size.toLong()) { url ->
      assertFailure { download(url, target) }
    }
    assertFalse(target.exists())
    assertEntries()
  }

  @Test fun emptyDeclaredResponseCannotReplacePreviousFile() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    response(byteArrayOf(), 0) { url -> assertFailure { download(url, target) } }
    assertArrayEquals(original, target.readBytes())
    assertEntries("cached.apk")
  }

  @Test fun emptyUnknownResponseCannotPublishAnApk() {
    val target = File(files.root, "new.apk")
    response(byteArrayOf(), null) { url -> assertFailure { download(url, target) } }
    assertFalse(target.exists())
    assertEntries()
  }

  @Test fun completeDeclaredResponseReplacesFileExactly() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    response(body, body.size.toLong()) { url -> download(url, target) }
    assertArrayEquals(body, target.readBytes())
    assertEntries("cached.apk")
  }

  @Test fun completeChunkedResponseReplacesFileExactly() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    response(body, null, chunked = true) { url -> download(url, target) }
    assertArrayEquals(body, target.readBytes())
    assertEntries("cached.apk")
  }

  @Test fun httpFailurePreservesPreviousFile() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    response(byteArrayOf(), 0, status = 503) { url ->
      assertFailure { download(url, target) }
    }
    assertArrayEquals(original, target.readBytes())
    assertEntries("cached.apk")
  }

  @Test fun validDownloadCanFollowFailedTransfer() {
    val target = files.newFile("cached.apk").apply { writeBytes(original) }
    response(body.copyOf(123), body.size.toLong()) { url ->
      assertFailure { download(url, target) }
    }
    assertArrayEquals(original, target.readBytes())
    response(body, null, chunked = true) { url -> download(url, target) }
    assertArrayEquals(body, target.readBytes())
    assertEntries("cached.apk")
  }

  private fun assertEntries(vararg names: String) =
      assertEquals(names.toSet(), files.root.list().orEmpty().toSet())

  private fun assertFailure(block: () -> Unit) {
    try { block(); fail("Incomplete or empty APK response must fail before publication") }
    catch (_: IOException) {}
  }

  private fun download(url: String, target: File) {
    if (consumer == "store") {
      StoreCatalog.download(url, target)
    } else {
      val method = UpdateManager::class.java.getDeclaredMethod("download", String::class.java, File::class.java)
      method.isAccessible = true
      try { method.invoke(UpdateManager, url, target) }
      catch (error: InvocationTargetException) { throw error.targetException }
    }
  }

  private fun response(bytes: ByteArray, length: Long?, chunked: Boolean = false,
      status: Int = 200, verify: (String) -> Unit) {
    ServerSocket(0, 1, InetAddress.getByName("127.0.0.1")).use { server ->
      val sent = AtomicBoolean()
      val fault = AtomicReference<Throwable?>()
      val worker = Thread {
        try {
          server.accept().use { socket ->
            socket.soTimeout = 2_000
            val headers = mutableListOf<String>()
            val reader = socket.getInputStream().bufferedReader(Charsets.US_ASCII)
            while (true) {
              val line = reader.readLine() ?: break
              if (line.isEmpty()) break
              headers.add(line)
              check(headers.sumOf { it.length } < 8192)
            }
            assertEquals("GET /generated.apk HTTP/1.1", headers.first())
            val ua = if (consumer == "store") "PortalStore/1.0" else "Immortal/1.0"
            assertTrue(headers.any { it.equals("User-Agent: $ua", ignoreCase = true) })
            val framing = if (chunked) "Transfer-Encoding: chunked\r\n"
                else length?.let { "Content-Length: $it\r\n" }.orEmpty()
            val head = "HTTP/1.1 $status Generated\r\n${framing}Connection: close\r\n\r\n"
            val out = socket.getOutputStream()
            out.write(head.toByteArray(Charsets.US_ASCII))
            if (chunked) {
              out.write("${bytes.size.toString(16)}\r\n".toByteArray(Charsets.US_ASCII))
              out.write(bytes)
              out.write("\r\n0\r\n\r\n".toByteArray(Charsets.US_ASCII))
            } else { out.write(bytes) }
            out.flush()
            sent.set(true)
          }
        } catch (error: Throwable) { fault.set(error) }
      }
      worker.isDaemon = true
      worker.start()
      try { verify("http://127.0.0.1:${server.localPort}/generated.apk") }
      finally {
        server.close()
        worker.join(2_000)
        assertFalse("Owned TCP fixture worker must finish", worker.isAlive)
        fault.get()?.let { throw it }
        assertTrue("The fixture must send its response", sent.get())
      }
    }
  }

  companion object {
    @JvmStatic @Parameterized.Parameters(name = "{0}")
    fun consumers() = listOf(arrayOf("store"), arrayOf("self-update"))
  }
}

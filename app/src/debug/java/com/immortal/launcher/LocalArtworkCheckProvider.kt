package com.immortal.launcher

import android.content.ContentProvider
import android.content.ContentValues
import android.database.Cursor
import android.net.Uri
import android.os.ParcelFileDescriptor
import android.os.SystemClock
import java.io.FileNotFoundException
import java.io.IOException
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.ConcurrentLinkedQueue
import java.util.concurrent.CountDownLatch
import java.util.concurrent.ExecutionException
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import java.util.concurrent.TimeoutException
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.atomic.AtomicInteger
import org.json.JSONObject

/** Debug-only loopback ContentResolver source: generated bytes, no backing files. */
class LocalArtworkCheckProvider : ContentProvider() {
  override fun onCreate() = true
  override fun getType(uri: Uri) = "image/png"
  override fun query(uri: Uri, projection: Array<out String>?, selection: String?,
      selectionArgs: Array<out String>?, sortOrder: String?): Cursor? = null
  override fun insert(uri: Uri, values: ContentValues?): Uri? = null
  override fun delete(uri: Uri, selection: String?, selectionArgs: Array<out String>?) = 0
  override fun update(uri: Uri, values: ContentValues?, selection: String?,
      selectionArgs: Array<out String>?) = 0

  override fun openFile(uri: Uri, mode: String): ParcelFileDescriptor {
    val current = session ?: throw FileNotFoundException()
    val parts = uri.pathSegments
    if (mode != "r" || uri.authority != "${context?.packageName}.local-artwork-check" ||
        parts.size != 2 || parts[0] != current.runId || parts[1] !in STAGES) {
      throw FileNotFoundException()
    }
    return current.open(parts[1])
  }

  internal class Session(
      val runId: String,
      private val png: ByteArray,
      private val deadline: Long,
      val failures: ConcurrentLinkedQueue<JSONObject>,
  ) {
    private val writers = Executors.newFixedThreadPool(4) { task ->
      Thread(task, "LocalArtworkPipe").apply { isDaemon = true }
    }
    private val pipes = ConcurrentHashMap.newKeySet<ParcelFileDescriptor>()
    private val stopping = AtomicBoolean(false)
    private val counts = STAGES.associateWith { AtomicInteger() }
    val firstByte = CountDownLatch(1)
    val releaseFirst = CountDownLatch(1)
    val firstWriterFinished = CountDownLatch(1)
    val firstBodySent = AtomicBoolean(false)
    val opens = AtomicInteger()

    fun count(stage: String) = counts.getValue(stage).get()
    fun descriptorsClosed() = pipes.isEmpty()

    @Synchronized fun open(stage: String): ParcelFileDescriptor {
      if (stopping.get() || SystemClock.elapsedRealtime() >= deadline ||
          count(stage) != 0) throw FileNotFoundException()
      val pair = ParcelFileDescriptor.createPipe()
      pipes.addAll(pair.toList())
      counts.getValue(stage).incrementAndGet()
      opens.incrementAndGet()
      try {
        writers.execute {
          try {
            ParcelFileDescriptor.AutoCloseOutputStream(pair[1]).use { output ->
              output.write(png, 0, 1)
              output.flush()
              if (stage == "first") {
                firstByte.countDown()
                val remaining = deadline - SystemClock.elapsedRealtime()
                if (remaining <= 0 ||
                    !releaseFirst.await(remaining, TimeUnit.MILLISECONDS)) {
                  throw TimeoutException()
                }
              }
              if (!stopping.get()) {
                output.write(png, 1, png.size - 1)
                output.flush()
                if (stage == "first") firstBodySent.set(true)
              }
            }
          } catch (failure: Throwable) {
            // Closed pipes and interruption are expected only during forced cleanup.
            if (!stopping.get() || failure !is IOException && failure !is InterruptedException) {
              failures.add(workerFailure("provider_$stage", failure))
            }
          } finally {
            closeDescriptor(pair[1])
            if (stage == "first") firstWriterFinished.countDown()
          }
        }
      } catch (failure: Throwable) {
        pair.forEach { closeDescriptor(it) }
        throw failure
      }
      return pair[0]
    }

    @Synchronized fun close() {
      stopping.set(true)
      releaseFirst.countDown()
      pipes.toList().forEach { closeDescriptor(it) }
      writers.shutdownNow()
    }

    fun awaitTermination(deadline: Long): Boolean =
        writers.awaitTermination(
            (deadline - SystemClock.elapsedRealtime()).coerceAtLeast(0),
            TimeUnit.MILLISECONDS)

    private fun closeDescriptor(descriptor: ParcelFileDescriptor) {
      try {
        descriptor.close()
        pipes.remove(descriptor)
      } catch (_: IOException) {
        failures.add(workerFailure("provider_close", IOException()))
      }
    }
  }

  companion object {
    private val STAGES = setOf("first", "cancelled", "other_one", "other_two")
    @Volatile internal var session: Session? = null

    internal fun failureKind(failure: Throwable): String = when (failure) {
      is ExecutionException -> failure.cause?.let { failureKind(it) } ?: "unexpected"
      is TimeoutException -> "timeout"
      is InterruptedException -> "interrupted"
      is IOException -> "io"
      is IllegalStateException, is IllegalArgumentException -> "assertion"
      else -> "unexpected"
    }

    internal fun workerFailure(stage: String, failure: Throwable): JSONObject =
        JSONObject().put("stage", stage).put("kind", failureKind(failure))
  }
}

(() => {
  const R = [];
  const dev = document.getElementById('device');
  const q = (s) => dev.querySelector(s);
  const click = (s) => { const el = typeof s === 'string' ? q(s) : s; if (!el) { R.push('MISSING ' + s); return; } el.click(); };
  const tileLabels = () => [...dev.querySelectorAll('.card.qc .qc-tile b')].map((b) => b.textContent).join('|');
  const ok = (name, cond) => R.push((cond ? 'PASS ' : 'FAIL ') + name);
  ok('home has 5 tiles', tileLabels() === 'Hey Jarvis|Lights|Scenes|Climate|Home');
  click('.qc-tile[data-label="Lights"]'); ok('lights landing', /Nothing in your home changed/.test(dev.textContent));
  click('[data-act="back"]'); ok('back to home', !!q('.card.qc'));
  click('[data-act="qc-heading"]'); ok('after: heading -> setup', /Live preview/.test(dev.textContent));
  click('[data-to="st:ha"]'); ok('setup -> ha page', /Home Assistant dashboard/.test(q('.st-head h2').textContent));
  click('[data-act="edit"]'); const a = document.getElementById('addr'); a.value = 'not a url'; a.dispatchEvent(new Event('input', { bubbles: true }));
  q('#editor-form').requestSubmit(); ok('invalid url rejected', /Enter a full/.test(dev.textContent));
  click('[data-act="fill"]'); q('#editor-form').requestSubmit(); ok('saved', /homeassistant\.local/.test(dev.textContent) && !q('.editor'));
  click('[data-act="back"]'); ok('setup preview updated', /Home dashboard/.test(q('.st-sub').textContent));
  click('[data-act="home"]'); ok('home tiles updated', tileLabels() === 'Hey Jarvis|Home dashboard');
  ok('HA widget shows dashboard', /Your home dashboard/.test(dev.textContent));
  click('.qc-tile[data-k="dash"]'); ok('dash landing', /Portal browser/.test(dev.textContent)); click('[data-act="back"]');
  click('.qc-tile[data-k="jarvis"]'); ok('jarvis landing', /Jarvis is listening/.test(dev.textContent)); click('[data-act="back"]');
  click('[data-act="customize"]'); click('[data-act="qc-customize-settings"]'); ok('after: customize -> setup', /Live preview/.test(dev.textContent));
  click('.row[data-act="apps"]'); click('[data-act="install"][data-k="jarvis"]'); ok('uninstall jarvis', document.querySelector('[data-sim="jarvis"]').checked === false);
  click('[data-act="home"]'); ok('home without jarvis', tileLabels() === 'Home dashboard');
  document.querySelector('[data-mode="before"]').click();
  click('[data-act="qc-heading"]'); ok('before: heading -> display', /Display/.test(q('.st-head h2').textContent) && /today’s behavior/.test(dev.textContent));
  click('[data-act="home"]'); click('[data-act="customize"]'); click('[data-act="qc-customize-settings"]'); ok('before: customize -> quick buttons', /Quick buttons/.test(q('.st-head h2').textContent));
  click('[data-act="home"]');
  const ha = document.querySelector('[data-sim="haApi"]'); ha.checked = true; ha.dispatchEvent(new Event('change'));
  ok('HA widget still dashboard while url saved', /Your home dashboard/.test(dev.textContent));
  document.querySelector('[data-tiles="rec"]').click();
  ok('rec mode dash tile', tileLabels() === 'Home dashboard');
  document.title = R.join('\n');
})();
